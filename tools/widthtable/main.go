// Command widthtable writes internal/textgrid/wide_table.go: the runes golang.org/x/text/width
// calls East Asian Wide or Fullwidth, as ranges. textgrid asks only that one question of the
// package, which linked 357 KB of trie into every build to answer it; the ranges are a few
// hundred bytes. Run it with `go generate ./internal/textgrid` after x/text moves to another
// Unicode version, or go.mod to another Go.
//
// x/text answers for the Unicode of the Go that builds it -- 15.0.0 below go1.27, 17.0.0 from
// it -- so this runs only under the Go release go.mod names, which CI and the release build
// with; under another it says which to ask for, as GOTOOLCHAIN=go1.26.10.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"runtime"
	"strings"

	"golang.org/x/text/width"
)

func main() {
	text, err := os.ReadFile("../../go.mod")
	if err != nil {
		log.Fatalf("run from internal/textgrid, by go generate: %v", err)
	}
	found := regexp.MustCompile(`(?m)^go (\d+\.\d+)`).FindSubmatch(text)
	if found == nil {
		log.Fatal("go.mod names no Go release")
	}
	release := "go" + string(found[1])
	if version := runtime.Version(); version != release && !strings.HasPrefix(version, release+".") {
		log.Fatalf("this is %s, and go.mod's is %s, whose x/text may be another Unicode: run it as GOTOOLCHAIN=%s.0 go generate ./internal/textgrid, or a later %s", version, release, release, release)
	}
	var ranges [][2]rune
	for r := rune(0); r <= 0x10FFFF; r++ {
		kind := width.LookupRune(r).Kind()
		if kind != width.EastAsianWide && kind != width.EastAsianFullwidth {
			continue
		}
		if last := len(ranges) - 1; last >= 0 && ranges[last][1] == r-1 {
			ranges[last][1] = r
			continue
		}
		ranges = append(ranges, [2]rune{r, r})
	}
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by tools/widthtable from golang.org/x/text/width, Unicode %s. DO NOT EDIT.\n\n", width.UnicodeVersion)
	fmt.Fprintf(&source, "package textgrid\n\n")
	fmt.Fprintf(&source, "// wideTableUnicode is the Unicode version x/text/width answered for, under %s.\n", runtime.Version())
	fmt.Fprintf(&source, "const wideTableUnicode = %q\n\n", width.UnicodeVersion)
	fmt.Fprintf(&source, "// wideRanges are the runes East Asian Wide or Fullwidth, %d ranges in order.\n", len(ranges))
	fmt.Fprintf(&source, "var wideRanges = [...][2]rune{\n")
	for _, span := range ranges {
		fmt.Fprintf(&source, "\t{0x%04X, 0x%04X},\n", span[0], span[1])
	}
	fmt.Fprintf(&source, "}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("wide_table.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
