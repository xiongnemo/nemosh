// Command widthtable writes internal/textgrid/wide_table.go: the runes golang.org/x/text/width
// calls East Asian Wide or Fullwidth, as ranges. textgrid asks only that one question of the
// package, which linked 357 KB of trie into every build to answer it; the ranges are a few
// hundred bytes. Run it with `go generate ./internal/textgrid`, from the repository's root or
// from there, after x/text moves to another Unicode version.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"

	"golang.org/x/text/width"
)

func main() {
	var ranges [][2]rune
	for r := rune(0); r <= 0x10FFFF; r++ {
		kind := width.LookupRune(r).Kind()
		if kind != width.EastAsianWide && kind != width.EastAsianFullwidth {
			continue
		}
		if last := len(ranges) - 1; last >= 0 && ranges[last][1] == r-1 {
			ranges[last][1] = r
			continue
		}
		ranges = append(ranges, [2]rune{r, r})
	}
	var source bytes.Buffer
	fmt.Fprintf(&source, "// Code generated by tools/widthtable from golang.org/x/text/width, Unicode %s. DO NOT EDIT.\n\n", width.UnicodeVersion)
	fmt.Fprintf(&source, "package textgrid\n\n")
	fmt.Fprintf(&source, "// wideRanges are the runes East Asian Wide or Fullwidth, %d ranges in order.\n", len(ranges))
	fmt.Fprintf(&source, "var wideRanges = [...][2]rune{\n")
	for _, span := range ranges {
		fmt.Fprintf(&source, "\t{0x%04X, 0x%04X},\n", span[0], span[1])
	}
	fmt.Fprintf(&source, "}\n")
	formatted, err := format.Source(source.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("wide_table.go", formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}
